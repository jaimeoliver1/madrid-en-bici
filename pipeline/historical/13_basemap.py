"""Background map for the site's maps and the 24h player: main roads, the Manzanares, big parks and a few landmarks.

Usage: python3 pipeline/historical/13_basemap.py <madrid.osm.pbf> site/basemap.js
The extract is Geofabrik's Madrid snapshot pinned in inputs.json. Needs pyosmium.
Coordinates are written as "lon,lat lon,lat ..." like the other map layers in data.js.
"""
import sys, json, math, osmium
from shapely.geometry import LineString, Polygon, box
from shapely.ops import linemerge, unary_union
from shapely import wkb as swkb

PBF, OUT = sys.argv[1], sys.argv[2]
BBOX = box(-3.80, 40.33, -3.56, 40.52)
ROADS = {"motorway": "m", "trunk": "m", "primary": "p", "secondary": "s"}
# Landmarks people navigate by: [es, en, lat, lon, tier] (tier 1 shows at full zoom-out)
PLACES = [
    ["Sol", "Sol", 40.4169, -3.7035, 1], ["Retiro", "Retiro", 40.4153, -3.6845, 2], ["Casa de Campo", "Casa de Campo", 40.4180, -3.7480, 1],
    ["Atocha", "Atocha", 40.4066, -3.6892, 2], ["Chamartín", "Chamartín", 40.4720, -3.6827, 1], ["Moncloa", "Moncloa", 40.4350, -3.7190, 1],
    ["Plaza de Castilla", "Plaza de Castilla", 40.4667, -3.6890, 2], ["Bernabéu", "Bernabéu", 40.4531, -3.6883, 2], ["Cibeles", "Cibeles", 40.4193, -3.6931, 2],
    ["Plaza de España", "Plaza de España", 40.4234, -3.7122, 2], ["Ciudad Universitaria", "University City", 40.4470, -3.7280, 2],
    ["Madrid Río", "Madrid Río", 40.3990, -3.7150, 2], ["Las Ventas", "Las Ventas", 40.4320, -3.6630, 2], ["Plaza Elíptica", "Plaza Elíptica", 40.3850, -3.7180, 2],
    ["Cuatro Caminos", "Cuatro Caminos", 40.4465, -3.7037, 2], ["Legazpi", "Legazpi", 40.3910, -3.6950, 2],
]
fab = osmium.geom.WKBFactory()
roads, rivers, parks = [], [], []

class H(osmium.SimpleHandler):
    def way(self, w):
        hw, ww = w.tags.get("highway"), w.tags.get("waterway")
        if hw not in ROADS and ww != "river": return
        try: g = swkb.loads(fab.create_linestring(w), hex=True)
        except Exception: return
        if not g.intersects(BBOX): return
        if hw in ROADS: roads.append((ROADS[hw], g))
        elif w.tags.get("name", "").startswith("Río Manzanares") or w.tags.get("name") == "Manzanares": rivers.append(g)
    def area(self, a):
        if a.tags.get("leisure") != "park" and a.tags.get("landuse") not in ("forest",) and a.tags.get("boundary") != "national_park": return
        try: g = swkb.loads(fab.create_multipolygon(a), hex=True)
        except Exception: return
        if not g.intersects(BBOX): return
        lat = g.centroid.y; km2 = g.area * (111.32 ** 2) * math.cos(math.radians(lat))
        if km2 >= 0.25: parks.append(g)

H().apply_file(PBF, locations=True)

def fmt(line, eps):
    l = line.simplify(eps)
    return " ".join(f"{x:.5f},{y:.5f}" for x, y in l.coords)

out = {"roads": [], "water": [], "parks": [], "places": PLACES}
for cls in ["m", "p", "s"]:
    merged = linemerge(unary_union([g for c, g in roads if c == cls]).intersection(BBOX))
    for l in getattr(merged, "geoms", [merged]):
        if l.length > (0.0015 if cls == "s" else 0.0005): out["roads"].append([cls, fmt(l, 0.00008)])
riv = linemerge(unary_union(rivers).intersection(BBOX))
for l in getattr(riv, "geoms", [riv]): out["water"].append(fmt(l, 0.00005))
pk = unary_union(parks).intersection(BBOX)
for p in getattr(pk, "geoms", [pk]):
    if p.geom_type != "Polygon" or p.area * 111.32 ** 2 * 0.76 < 0.25: continue
    out["parks"].append(fmt(p.exterior, 0.0001))
open(OUT, "w").write("/* generated by pipeline/historical/13_basemap.py from OpenStreetMap (ODbL) */\nwindow.BASE = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n")
print({k: len(v) for k, v in out.items()}, "bytes", sum(len(x[1]) if isinstance(x, list) else len(x) for k in ("roads", "water", "parks") for x in out[k]))
